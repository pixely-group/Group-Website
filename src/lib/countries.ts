/**
 * National outlines for the country plate on the globe's readout, in
 * [longitude, latitude].
 *
 * Generated from Natural Earth 1:50m admin-0 (public domain), by way of
 * world-atlas' countries-50m TopoJSON: arcs decoded, rings kept above five
 * thousandths of the country's largest and capped at the six biggest, then
 * Douglas-Peucker to a budget of a hundred and fifty points. The 110m tier
 * this used to come from was too blunt for the small countries — Qatar was
 * eight points and had none of its shape — so the whole set moved up a tier.
 * The source file is not kept; this is the whole of it.
 *
 * Territory is left out where it is real but drags the bounding box across
 * an ocean, which leaves the country a speck in the corner of its own plate:
 * Alaska and Hawaii, the Canaries, the Ryukyus (900km south-west of Kyushu),
 * Shetland, Russia's slice past the antimeridian. What is drawn is the
 * silhouette each country is recognised by, which is the plate's whole job.
 * It is also why these boxes read a degree or two short of an atlas.
 *
 * Russia is folded rather than clipped: its mainland ring is the one that
 * wraps the antimeridian, so dropping that ring deletes the country. The
 * overhang past 180 is folded back onto the dateline.
 *
 * Holes are real holes: Lesotho is a hole in South Africa, so the plate
 * fills these evenodd rather than nonzero.
 *
 * SG is hand-cut. Natural Earth gives Singapore nine points even at 50m — a
 * blob with its corners knocked off — so it is drawn from the real coastline:
 * Tuas at the west tip, the south coast past Jurong and Keppel, Changi east,
 * and the Johor Strait back along the indented north.
 *
 * PS comes from a supplied governorate map rather than Natural Earth: sixteen
 * governorates, eleven in the West Bank and five in Gaza, unioned by cancelling
 * every border drawn twice — a shared border appears once in each direction,
 * so what survives is the outside of the whole set. 1287 edges in, 205 out,
 * closing into exactly two loops with nothing left over, then simplified to
 * the same budget as the rest. It is a finer line than the fifty points
 * Natural Earth gave the same country.
 */
