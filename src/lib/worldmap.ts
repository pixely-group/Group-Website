/**
 * Every coastline segment, flattened, and an index of them by latitude.
 *
 * Both tests below ask a question about one latitude at a time: the ray-cast
 * only cares about segments that straddle the point's latitude, and the
 * shore test only about segments within a fraction of a degree of it. So the
 * segments are bucketed into one-degree bands once, and a point looks at the
 * forty-odd in its own band instead of all 5,795.
 *
 * This is the whole difference between a globe that appears and a globe that
 * arrives three seconds late. Culling by ring bounding box — the obvious
 * first move, and the one that stood here — does almost nothing, because the
 * rings that matter are continents: their boxes span half the planet, so
 * every point in the Atlantic falls inside Eurasia's box and walks all
 * fifteen hundred of its segments to find that out.
 */
const SEG: number[] = [];
const BAND: number[][] = Array.from({ length: 181 }, () => []);
for (const ring of WORLD) {
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const n = SEG.length / 4;
    SEG.push(ring[j][0], ring[j][1], ring[i][0], ring[i][1]);
    const lo = Math.max(0, Math.floor(Math.min(ring[j][1], ring[i][1]) + 90));
    const hi = Math.min(180, Math.ceil(Math.max(ring[j][1], ring[i][1]) + 90));
    for (let b = lo; b <= hi; b++) BAND[b].push(n);
  }
}
const band = (lat: number) =>
  BAND[Math.max(0, Math.min(180, Math.floor(lat + 90)))];

